#!/usr/bin/env python3
"""Dev-only secret generator (stdlib only). Never real secrets, never commit output.

Generates random placeholders for local development:
  SESSION_SIGNING_SECRET, GATEWAY_DATA_KEY_B64,
  SIMULATOR_ED25519_SEED_B64 / SIMULATOR_ED25519_PUB_B64 (dev seeds, not real keys),
  synthetic wallet placeholders (OWNER/READER_ADDRESS).

Ed25519 key derivation needs the `cryptography` lib at runtime; this script only
emits a random 32-byte dev seed. Real key handling lands in PG-010/PG-011.

Usage:
  python infra/scripts/keygen.py --help
  python infra/scripts/keygen.py                # print to stdout (copy into untracked .env)
  python infra/scripts/keygen.py --out .env     # write file (refuses to overwrite without --force)
"""
from __future__ import annotations

import argparse
import base64
import secrets

DEV_WALLET_NOTE = "synthetic dev-only placeholder, not a funded key"


def _b64(n: int) -> str:
    return base64.b64encode(secrets.token_bytes(n)).decode("ascii")


def _addr() -> str:
    return "0x" + secrets.token_hex(20)


def generate() -> dict[str, str]:
    return {
        "SESSION_SIGNING_SECRET": secrets.token_hex(32),
        "GATEWAY_DATA_KEY_B64": _b64(32),
        "SIMULATOR_ED25519_SEED_B64": _b64(32),
        "SIMULATOR_ED25519_PUB_B64": _b64(32),
        "OWNER_ADDRESS": _addr(),
        "READER_ADDRESS": _addr(),
    }


def render(values: dict[str, str]) -> str:
    lines = [
        "# Generated by infra/scripts/keygen.py — DEV ONLY. Do not commit. " + DEV_WALLET_NOTE + ".",
    ]
    for k, v in values.items():
        lines.append(f"{k}={v}")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="", help="Write to file instead of stdout.")
    ap.add_argument("--force", action="store_true", help="Allow overwriting --out file.")
    args = ap.parse_args()

    text = render(generate())
    if not args.out:
        print(text, end="")
        return
    import os

    if os.path.exists(args.out) and not args.force:
        ap.error(f"{args.out} exists; pass --force to overwrite")
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {args.out} (dev-only, do not commit)")


if __name__ == "__main__":
    main()
